  // Pitch follows engine RPM, volume follows pedal opening. Because triggerShift() moves
  // the gear immediately while isShifting only clears later, the revs drop on the very
  // same tick — so the note audibly falls at each upshift and climbs again, instead of
  // rising monotonically with road speed as it used to.
  let engineIdleSince = null;
  function updateEngineSound(throttleMagnitude) {
    if (!soundEnabled || !engineOsc) return;
    const st = physEngine.state, p = soundProfile;
    let pitchNorm, load;
    if (physicsEnabled) {
      pitchNorm = st.rpmFrac;
      load = st.engineLoad;
    } else {
      pitchNorm = load = Math.abs(throttleMagnitude); // raw mode: unchanged behaviour
    }
    // RPM never drops below idle, so without this the engine would hum forever after load.
    const busy = load > 0.01 || st.virtualSpeed > 0.01;
    const now = Date.now();
    if (busy) engineIdleSince = null;
    else if (engineIdleSince === null) engineIdleSince = now;
    const silent = !busy && engineIdleSince !== null && now - engineIdleSince > 4000;

    // Sample engine takes over when a car is loaded and playing; the oscillator path below
    // stays intact as the fallback for the synthetic profiles and for missing audio/.
    // Squeal only under real braking above walking pace, so it does not chirp on every
    // light touch of the trigger.
    const brakeAmt = (physicsEnabled && st.speedKmh > physEngine.config.topSpeedKmh * 0.12)
      ? Math.max(0, Math.min(1, (Math.max(0, -throttleY) - 0.25) / 0.55)) : 0;
    setBrakeSqueal(brakeAmt);
    // Der Reibkreis-Querbedarf treibt es. Er steht im Zustand, weil er hier gebraucht wird.
    setTyreSqueal(physEngine.state.latUse || 0);

    if (sampleEngine.nodes && physicsEnabled) { updateSampleEngine(st.rpm, load, silent); return; }

    const freq = p.baseFreq + Math.max(0, Math.min(1, pitchNorm)) * p.freqSpan;
    let gain = p.gainBase * (0.35 + 0.65 * pitchNorm) + load * p.gainSpan;
    if (st.onLimiter) gain *= 0.75 + 0.25 * Math.sign(Math.sin(now / 18)); // limiter flutter
    if (silent) gain = 0;
    const t = audioCtx.currentTime;
    engineOsc.frequency.setTargetAtTime(freq, t, 0.03); // 0.03: don't smear the shift drop
    engineGain.gain.setTargetAtTime(gain, t, 0.05);
  }

  // Short synthesized impact: a burst of white noise through a fast decay envelope.
  function playCrashSound() {
    if (!soundEnabled || !audioCtx) return;
    const dur = 0.45;
    const buffer = audioCtx.createBuffer(1, Math.floor(audioCtx.sampleRate * dur), audioCtx.sampleRate);
    const data = buffer.getChannelData(0);
    for (let i = 0; i < data.length; i++) {
      data[i] = (Math.random() * 2 - 1) * (1 - i / data.length); // noise, decaying
    }
    const src = audioCtx.createBufferSource();
    src.buffer = buffer;
    const g = audioCtx.createGain();
    const t = audioCtx.currentTime;
    g.gain.setValueAtTime(0.5, t);
    g.gain.exponentialRampToValueAtTime(0.001, t + dur);
    const lp = audioCtx.createBiquadFilter();
    lp.type = 'lowpass';
    lp.frequency.setValueAtTime(1200, t);
    src.connect(lp).connect(g).connect(audioCtx.destination);
    src.start();
    src.stop(t + dur);
  }


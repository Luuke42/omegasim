  function playAmbienceOneShot(buffer, gain, wet) {
    if (!buffer || !audioCtx || !soundEnabled || !ambienceEnabled || ambience.busy) return;
    ambience.busy = true;                      // never let an event overlap itself
    const src = audioCtx.createBufferSource();
    src.buffer = buffer;
    const g = audioCtx.createGain();
    g.gain.value = gain * (wet ? rainVolume : ambienceVolume);
    const pan = audioCtx.createStereoPanner
      ? audioCtx.createStereoPanner() : null;
    if (pan) {
      pan.pan.value = Math.random() * 1.6 - 0.8;
      src.connect(g).connect(pan).connect(audioCtx.destination);
    } else {
      src.connect(g).connect(audioCtx.destination);
    }
    src.onended = () => { ambience.busy = false; };
    src.start();
  }

  function scheduleAmbienceEvent() {
    // Thunder every 20-30s while it rains (user's spec); otherwise a pass-by every 8-25s.
    // Timing follows the WEATHER, not the audio: the storm exists whether or not the
    // ambience is audible, so the interval must not depend on loaded buffers either.
    const storm = weather === 'rain';
    const wait = storm ? 20000 + Math.random() * 10000 : 8000 + Math.random() * 17000;
    setTimeout(() => {
      if (storm) {
        // Light before sound, the way it actually arrives: the flash fires now, the clap
        // about 200 ms later. The FLASH is outside the audio gate on purpose — muting the
        // ambience must not turn the lightning off as well, or a silent storm becomes an
        // invisible one.
        triggerLightning();
        if (ambience.ready && ambienceEnabled && ambience.thunder.length) {
          const clap = ambience.thunder[Math.floor(Math.random() * ambience.thunder.length)];
          const gain = 0.55 + Math.random() * 0.45;
          setTimeout(() => playAmbienceOneShot(clap, gain, true), 200);
        }
      } else if (ambience.ready && ambienceEnabled && ambience.passby.length) {
        playAmbienceOneShot(ambience.passby[Math.floor(Math.random() * ambience.passby.length)],
                            0.35 + Math.random() * 0.45);
      }
      scheduleAmbienceEvent();
    }, wait);
  }

  function stopSampleEngine() {
    if (!sampleEngine.nodes) return;
    for (const n of sampleEngine.nodes) { try { n.src.stop(); } catch (e) { /* already stopped */ } }
    if (sampleEngine.over) { try { sampleEngine.over.src.stop(); } catch (e) { /* already stopped */ } }
    sampleEngine.nodes = null;
    sampleEngine.over = null;
    sampleEngine.car = null;
    if (sampleEngine.master) sampleEngine.master.gain.setTargetAtTime(0, audioCtx.currentTime, 0.03);
  }

  function startSampleEngine(car) {
    if (!sampleEngine.ready || !sampleEngine.buffers[car]) return false;
    stopSampleEngine();
    if (!sampleEngine.master) {
      sampleEngine.master = audioCtx.createGain();
      sampleEngine.master.gain.value = 0;
      sampleEngine.master.connect(audioCtx.destination);
    }
    // All three start together so they stay phase-consistent for the whole session.
    const t0 = audioCtx.currentTime + 0.04;
    sampleEngine.nodes = BANDS.map(band => {
      const info = sampleEngine.buffers[car][band];
      const src = audioCtx.createBufferSource();
      src.buffer = info.buffer;
      src.loop = true;
      const g = audioCtx.createGain();
      g.gain.value = 0;
      src.connect(g).connect(sampleEngine.master);
      src.start(t0);
      return { src, gain: g, baseRpm: info.baseRpm };
    });
    // The overrun voice runs in PARALLEL to the three power bands, not as a fourth rpm
    // anchor: it is a different operating state, not a different engine speed. One file per
    // engine is enough because it is pitched by rpm exactly like the others.
    const ov = sampleEngine.buffers[car].over;
    if (ov) {
      const src = audioCtx.createBufferSource();
      src.buffer = ov.buffer;
      src.loop = true;
      const g = audioCtx.createGain();
      g.gain.value = 0;
      src.connect(g).connect(sampleEngine.master);
      src.start(t0);
      sampleEngine.over = { src, gain: g, baseRpm: ov.baseRpm };
    }
    sampleEngine.car = car;
    if (engineGain) engineGain.gain.setTargetAtTime(0, audioCtx.currentTime, 0.05); // hush the oscillator
    return true;
  }

  // Triangular crossfade between the three anchors. The weights always sum to exactly 1,
  // so moving through the rev range can never produce a hole or a bulge in loudness.
  function sampleWeights(rpm, b) {
    const w = [0, 0, 0];
    if (rpm <= b[0]) w[0] = 1;
    else if (rpm >= b[2]) w[2] = 1;
    else if (rpm <= b[1]) { const t = (rpm - b[0]) / (b[1] - b[0]); w[0] = 1 - t; w[1] = t; }
    else { const t = (rpm - b[1]) / (b[2] - b[1]); w[1] = 1 - t; w[2] = t; }
    return w;
  }

  // Doppler at the line. A trackside listener hears an approaching car high and a
  // departing one low, and the crossing is where the sign flips. The physical ratio at
  // scale speed would be about 1.6 either way, which is what a real flyby sounds like and
  // completely absurd for a sound the driver hears continuously — so the swing is scaled by
  // speed and capped well below the physical value. It is a cue, not a simulation.
  const DOPPLER_MAX = 0.10;      // +-10 % at the top of the speed range
  const DOPPLER_S = 0.45;        // how long the sweep takes
  let dopplerStart = 0;
  function triggerDoppler() {
    if (!sampleEngine.nodes || !audioCtx) return;
    dopplerStart = audioCtx.currentTime;
  }
  function dopplerFactor() {
    if (!dopplerStart || !audioCtx) return 1;
    const u = (audioCtx.currentTime - dopplerStart) / DOPPLER_S;
    if (u < 0 || u > 1) { dopplerStart = 0; return 1; }
    const frac = Math.min(1, Math.abs(physEngine.state.speedKmh) / physEngine.config.topSpeedKmh);
    // cos over the window: starts high, passes through unity at the middle, ends low.
    return 1 + Math.cos(u * Math.PI) * DOPPLER_MAX * frac;
  }

  function updateSampleEngine(rpm, load, silent) {
    const nodes = sampleEngine.nodes;
    const scale = sampleEngine.rpmScale[sampleEngine.car] || 1;
    // The crossfade has to see the same scaled rpm as the playback rate does, otherwise the
    // band boundaries and the pitch disagree and you hear the wrong loop at the wrong speed.
    const w = sampleWeights(rpm * scale, nodes.map(n => n.baseRpm));
    const t = audioCtx.currentTime;
    // How much of the power sound against the overrun sound. Closed at a trace of throttle
    // rather than at exactly zero, because a real engine is back on the gas well before the
    // pedal is fully down, and a crossfade that only completes at load = 0 spends most of
    // its travel doing nothing audible.
    const over = sampleEngine.over;
    const powerMix = over ? Math.min(1, Math.max(0, (load - 0.06) / 0.30)) : 1;
    const dop = dopplerFactor();
    nodes.forEach((n, i) => {
      // A loop generated at baseRpm played back at rpm/baseRpm IS that engine speed.
      // Clamped because resampling much beyond an octave stops sounding like an engine —
      // past that the neighbouring loop has taken over anyway.
      const rate = Math.max(0.5, Math.min(2.0, rpm * scale / n.baseRpm * dop));
      n.src.playbackRate.setTargetAtTime(rate, t, 0.04);
      n.gain.gain.setTargetAtTime(w[i] * powerMix, t, 0.05);
    });
    if (over) {
      const rate = Math.max(0.5, Math.min(2.0, rpm * scale / over.baseRpm * dop));
      over.src.playbackRate.setTargetAtTime(rate, t, 0.04);
      over.gain.gain.setTargetAtTime(1 - powerMix, t, 0.05);
    }
    // With a real overrun loop the master no longer has to fake off-throttle by turning
    // down — the quieter, crackling sound does that itself. Ducking it as hard as before
    // would just hide the loop that was made for this.
    let vol = engineVolume * (over ? 0.55 + 0.45 * load : 0.25 + 0.75 * load);
    if (physEngine.state.onLimiter) vol *= 0.8 + 0.2 * Math.sign(Math.sin(Date.now() / 18));
    sampleEngine.master.gain.setTargetAtTime(silent ? 0 : vol, t, 0.05);
  }

